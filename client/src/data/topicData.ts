export const INDUSTRIES = TOPICS.filter(t => t.category === "industry");
export const INTERESTS = TOPICS.filter(t => t.category === "interest");
export const ROLES = TOPICS.filter(t => t.category === "role");

export function getCategoryPath(category: TopicCategory): string {
  switch (category) {
    case "industry": return "/industries";
    case "interest": return "/interests";
    case "role": return "/roles";
  }
}

export function getTopicBySlug(slug: string): TopicConfig | undefined {
  return TOPICS.find(t => t.slug === slug);
}
